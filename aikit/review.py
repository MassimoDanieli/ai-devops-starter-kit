"""Diff-based code review with structured findings.

Differences from the 2025 version:
- reviews the *diff* of the PR (with context), not whole files one by one;
- asks for a fixed structure (file, line, severity, fix) instead of free prose;
- tells the model to stay quiet when there is nothing worth saying, because
  low-value comments are the main reason review bots get ignored.
"""

from __future__ import annotations

from typing import Any

from .client import AIClient, strict_object

MAX_DIFF_CHARS = 180_000

SEVERITIES = ["critical", "major", "minor"]

SCHEMA = strict_object(
    {
        "summary": {"type": "string", "description": "2-4 sentences on what the change does and its overall risk."},
        "verdict": {"type": "string", "enum": ["looks_good", "minor_issues", "needs_changes"]},
        "findings": {
            "type": "array",
            "items": strict_object(
                {
                    "file": {"type": "string"},
                    "line": {"type": "integer", "description": "Line in the new version of the file; 0 if not applicable."},
                    "severity": {"type": "string", "enum": SEVERITIES},
                    "category": {
                        "type": "string",
                        "enum": ["bug", "security", "performance", "reliability", "maintainability", "tests"],
                    },
                    "title": {"type": "string"},
                    "explanation": {"type": "string"},
                    "suggested_fix": {"type": "string", "description": "Concrete code or steps; empty string if none."},
                }
            ),
        },
    }
)

SYSTEM = """You are a senior engineer reviewing a pull request diff.
Report only problems a careful human reviewer would want fixed before merge:
bugs, security issues, data loss, broken error handling, race conditions,
performance traps, missing tests for risky logic.
Do NOT report style nits, formatting, naming preferences or praise.
Every finding must point at a specific file and line in the diff and include
a concrete suggested fix. If the change is fine, return an empty findings list.
Write in {language}."""


def build_prompt(diff_text: str, extra_context: str = "") -> str:
    truncated = ""
    if len(diff_text) > MAX_DIFF_CHARS:
        diff_text = diff_text[:MAX_DIFF_CHARS]
        truncated = "\n\n[diff truncated: review only what is shown]"
    ctx = f"Project context:\n{extra_context.strip()}\n\n" if extra_context.strip() else ""
    return f"{ctx}Diff to review:\n```diff\n{diff_text}\n```{truncated}"


def review_diff(client: AIClient, diff_text: str, language: str = "English", extra_context: str = "") -> dict[str, Any]:
    if not diff_text.strip():
        return {"summary": "Empty diff: nothing to review.", "verdict": "looks_good", "findings": []}
    return client.complete(
        SYSTEM.format(language=language),
        build_prompt(diff_text, extra_context),
        schema=SCHEMA,
        schema_name="code_review",
    )


_ICON = {"critical": "🔴", "major": "🟠", "minor": "🟡"}
_VERDICT = {"looks_good": "✅ Looks good", "minor_issues": "🟡 Minor issues", "needs_changes": "🔴 Needs changes"}


def to_markdown(result: dict[str, Any], model_label: str = "") -> str:
    findings = sorted(result["findings"], key=lambda f: SEVERITIES.index(f["severity"]))
    lines = [f"## AI review — {_VERDICT.get(result['verdict'], result['verdict'])}", "", result["summary"], ""]
    if not findings:
        lines.append("No issues worth flagging.")
    for f in findings:
        loc = f"`{f['file']}`" + (f":{f['line']}" if f["line"] else "")
        lines += [f"### {_ICON[f['severity']]} {f['title']}", f"{loc} · {f['severity']} · {f['category']}", "", f["explanation"]]
        if f["suggested_fix"].strip():
            lines += ["", "<details><summary>Suggested fix</summary>", "", f["suggested_fix"].strip(), "", "</details>"]
        lines.append("")
    if model_label:
        lines.append(f"<sub>Generated by ai-devops-starter-kit · {model_label}</sub>")
    return "\n".join(lines).rstrip() + "\n"


def should_fail(result: dict[str, Any], fail_on: str | None) -> bool:
    """True if any finding is at or above ``fail_on`` severity."""
    if not fail_on:
        return False
    threshold = SEVERITIES.index(fail_on)
    return any(SEVERITIES.index(f["severity"]) <= threshold for f in result["findings"])
