"""Suggest (and optionally write) missing tests for the files a PR changes.

Unlike the 2025 Streamlit tool, this works on real source files from the
diff, returns runnable test files rather than prose, and never overwrites
existing tests: proposals land in a separate folder for a human to adopt.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from .client import AIClient, strict_object

MAX_FILE_CHARS = 40_000
CODE_SUFFIXES = {".py", ".js", ".ts", ".tsx", ".jsx", ".go", ".java", ".kt", ".rb", ".rs", ".sh", ".cs"}

SCHEMA = strict_object(
    {
        "proposals": {
            "type": "array",
            "items": strict_object(
                {
                    "target_file": {"type": "string"},
                    "test_file": {"type": "string", "description": "Repo-relative path for the new test file."},
                    "framework": {"type": "string"},
                    "covers": {"type": "array", "items": {"type": "string"}, "description": "Behaviours the tests pin down."},
                    "code": {"type": "string", "description": "Complete, runnable test file."},
                }
            ),
        }
    }
)

SYSTEM = """You write focused, runnable unit tests.
For each source file, look at the changed lines in the diff and write tests
for the behaviour that changed: edge cases, error paths, boundary values.
Use the test framework the repository already uses (see the existing test
files listed). Do not test private helpers through hacks, do not call the
network, and do not duplicate tests that already exist.
If a file needs no new tests, leave it out. Write comments in {language}."""


def is_code(path: str) -> bool:
    p = Path(path)
    name = p.name.lower()
    if p.suffix not in CODE_SUFFIXES:
        return False
    return not (name.startswith("test_") or "_test." in name or ".test." in name or ".spec." in name or "/tests/" in f"/{path}")


def build_prompt(diff_text: str, files: dict[str, str], existing_tests: list[str]) -> str:
    parts = ["Diff:\n```diff\n" + diff_text[:60_000] + "\n```", ""]
    parts.append("Existing test files: " + (", ".join(existing_tests[:50]) or "none"))
    for path, content in files.items():
        parts.append(f"\n--- {path} ---\n```\n{content[:MAX_FILE_CHARS]}\n```")
    return "\n".join(parts)


def propose(
    client: AIClient, diff_text: str, files: dict[str, str], existing_tests: list[str], language: str = "English"
) -> dict[str, Any]:
    if not files:
        return {"proposals": []}
    return client.complete(
        SYSTEM.format(language=language),
        build_prompt(diff_text, files, existing_tests),
        schema=SCHEMA,
        schema_name="test_proposals",
    )


def write_proposals(result: dict[str, Any], out_dir: str | Path) -> list[Path]:
    """Write proposals under ``out_dir`` keeping their relative paths. Refuses
    paths that would escape ``out_dir``."""
    root = Path(out_dir).resolve()
    written = []
    for p in result["proposals"]:
        dest = (root / p["test_file"].lstrip("/")).resolve()
        if root not in dest.parents:
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(p["code"].rstrip() + "\n", encoding="utf-8")
        written.append(dest)
    return written


def to_markdown(result: dict[str, Any], model_label: str = "") -> str:
    if not result["proposals"]:
        body = "## AI test suggestions\n\nNo missing tests found for the changed files.\n"
    else:
        lines = ["## AI test suggestions", ""]
        for p in result["proposals"]:
            lines += [
                f"### `{p['test_file']}` → covers `{p['target_file']}` ({p['framework']})",
                *[f"- {c}" for c in p["covers"]],
                "",
                "<details><summary>Proposed test file</summary>",
                "",
                "```",
                p["code"].rstrip(),
                "```",
                "",
                "</details>",
                "",
            ]
        body = "\n".join(lines)
    if model_label:
        body = body.rstrip() + f"\n\n<sub>Generated by ai-devops-starter-kit · {model_label}</sub>\n"
    return body
